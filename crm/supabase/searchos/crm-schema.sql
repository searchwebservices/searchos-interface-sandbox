CREATE OR REPLACE FUNCTION "crm"."cleanup_note_attachments"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
    DECLARE
      payload jsonb;
      request_headers jsonb;
      auth_header text;
    BEGIN
      request_headers := coalesce(
        nullif(current_setting('request.headers', true), '')::jsonb,
        '{}'::jsonb
      );
      auth_header := request_headers ->> 'authorization';

      IF auth_header IS NULL OR auth_header = '' THEN
        IF TG_OP = 'DELETE' THEN
          RETURN OLD;
        END IF;

        RETURN NEW;
      END IF;

      payload := jsonb_build_object(
        'old_record', OLD,
        'record', NEW,
        'type', TG_OP
      );

      -- SearchOS: this only calls our own project's delete_note_attachments edge
      -- function (pg_net, async). If pg_net is missing or the call fails, the note
      -- change still goes through and the attachment is simply left in storage.
      begin
        PERFORM net.http_post(
          url := crm.get_note_attachments_function_url(),
          body := payload,
          params := '{}'::jsonb,
          headers := jsonb_build_object(
            'Content-Type',
            'application/json',
            'Authorization',
            auth_header
          ),
          timeout_milliseconds := 10000
        );
      exception when others then
        null;
      end;

      IF TG_OP = 'DELETE' THEN
        RETURN OLD;
      END IF;

      RETURN NEW;
    END;
    $$;

